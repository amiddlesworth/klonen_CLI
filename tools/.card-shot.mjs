import { chromium } from 'playwright';
const [,, url, text, out, w = '1440'] = process.argv;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: +w, height: 900 }, colorScheme: process.env.THEME === 'dark' ? 'dark' : 'light' });
await ctx.addCookies([{ name: 'cn_demo_session', value: process.env.ROLE || 'coach', domain: 'localhost', path: '/' }]);
const page = await ctx.newPage();
await page.goto(url, { waitUntil: 'networkidle', timeout: 90000 });
const el = page.locator('article, section').filter({ hasText: text }).last();
await el.screenshot({ path: out });
console.log('saved', out);
await browser.close();
